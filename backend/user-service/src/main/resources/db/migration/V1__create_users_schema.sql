-- =====================================================
-- ROLES
-- =====================================================

CREATE TABLE roles
(
    id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,

    CONSTRAINT uk_roles_name UNIQUE (name)
);


-- =====================================================
-- USERS
-- =====================================================

CREATE TABLE users
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username   VARCHAR(32),
    password   VARCHAR(255) NOT NULL,
    name       VARCHAR(64) NOT NULL,
    avatar_path VARCHAR(255),

    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    is_blocked BOOLEAN NOT NULL DEFAULT FALSE,
    is_online  BOOLEAN NOT NULL DEFAULT FALSE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    last_seen  TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    theme      BOOLEAN NOT NULL DEFAULT FALSE,
    bio        VARCHAR(255),

    CONSTRAINT uk_users_username UNIQUE (username)
);


-- =====================================================
-- USER ROLES
-- =====================================================

CREATE TABLE user_roles
(
    users_id BIGINT NOT NULL,
    roles_id INTEGER NOT NULL,

    CONSTRAINT fk_user_roles_user
        FOREIGN KEY (users_id) REFERENCES users (id),

    CONSTRAINT fk_user_roles_role
        FOREIGN KEY (roles_id) REFERENCES roles (id),

    CONSTRAINT uc_rd_uid UNIQUE (roles_id, users_id)
);


-- =====================================================
-- CONTACTS
-- =====================================================

CREATE TABLE contacts
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id_1  BIGINT,
    user_id_2  BIGINT,
    added_at   TIMESTAMPTZ,
    alias      VARCHAR(64) NOT NULL,

    CONSTRAINT fk_contacts_owner
        FOREIGN KEY (user_id_1) REFERENCES users (id),

    CONSTRAINT fk_contacts_user
        FOREIGN KEY (user_id_2) REFERENCES users (id)
);

CREATE INDEX idx_contacts_user_id_1
    ON contacts (user_id_1);

CREATE INDEX idx_contacts_user_id_2
    ON contacts (user_id_2);


-- =====================================================
-- DEACTIVATED TOKENS
-- =====================================================

CREATE TABLE deactivated_tokens
(
    id         UUID PRIMARY KEY,
    expiration TIMESTAMPTZ NOT NULL
);


